import glob, hashlib, html, os, re
from html.parser import HTMLParser

P = "private_html"
OUT = P + "/_audio_text"
os.makedirs(OUT, exist_ok=True)
SKIPCLS = {"sheet", "legend"}
SKIPID = {"toc", "refs", "sheet"}
BREAK = {"p", "li", "br", "h1", "h2", "h3", "h4", "h5", "tr", "caption", "summary", "div"}


class X(HTMLParser):

    def __init__(s):
        super().__init__()
        s.stack = []
        s.skip = 0
        s.out = []
        s.inart = 0

    def handle_starttag(s, t, a):
        a = dict(a)
        cls = set((a.get("class") or "").split())
        if t in ("br", "img", "input", "meta", "link", "hr"):
            if t == "br" and s.inart and not s.skip:
                s.out.append("。")
            return
        sk = (
            s.skip > 0
            or (cls & SKIPCLS)
            or a.get("id") in SKIPID
            or t in ("nav", "script", "style", "sup", "details", "aside")
        )
        if "article-content" in cls:
            s.inart += 1
        s.stack.append((t, bool(sk), "article-content" in cls))
        if sk:
            s.skip += 1

    def handle_endtag(s, t):
        while s.stack:
            tt, sk, ac = s.stack.pop()
            if sk:
                s.skip -= 1
            if ac:
                s.inart -= 1
            if s.inart and not s.skip:
                if tt in BREAK:
                    s.out.append("。")
                elif tt in ("td", "th"):
                    s.out.append("、")
            if tt == t:
                break

    def handle_data(s, d):
        if s.inart and not s.skip:
            s.out.append(d)


