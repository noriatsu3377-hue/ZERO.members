EXACT_REPLACEMENTS = [
    (k, "オーエーアールエスアイ" if v == "オarsi" else v)
    for k, v in EXACT_REPLACEMENTS
]
# Sort longest first so longer compounds match before substrings
EXACT_REPLACEMENTS.sort(key=lambda x: len(x[0]), reverse=True)


def normalize_japanese_readings(t: str) -> str:
    # 1. Exact replacements (longest match first)
    for src, dst in EXACT_REPLACEMENTS:
        if src and src in t:
            t = t.replace(src, dst)

    # 2. Standalone "筋" (when not part of 筋肉/筋力/筋膜/経筋/背筋/腹筋/殿筋/首筋/道筋/筋道)
    # e.g., "その筋たちを束ね" -> "そのキンたちを束ね", "単一の筋" -> "単一のキン"
    t = re.sub(r"(?<![一-龥ァ-ヶー])筋(?![肉力膜道]|群|たち)", "キン", t)
    t = t.replace("筋たち", "キンたち")

    # 3. Context-sensitive "方" (patient/person vs comparison/direction)
    # In these clinical articles, "〜の方" refers to patients/people ("かた"),
    # EXCEPT in comparative expressions like "〜の方が(高い|低い|良い|いい|よい|多い|少ない|強い|弱い|早い|遅い|安全|大事|重要|自然|確実|有効|適)"
    # or directional nouns like "見方/考え方/やり方/触れ方/聞き方/伝え方/作り方/使い方/進め方/選び方/読み方/捉え方/座り方/立ち方/歩き方/走り方/寝方/出方/動き方/働き方/関わり方/向き合い方/付き合い方"
    def replace_kata(m):
        full = m.group(0)
        after = m.group(2)
        if re.match(
            r"^が(高|低|良|いい|よ|やす|多|少|強|弱|安全|早|遅|先|大|小|長|短|深|浅|楽|大事|重要|自然|確実|有効|適)",
            after,
        ):
            return full
        return m.group(1) + "かた" + after

    t = re.sub(
        r"(の|た|る|い|な|同じ|他の|別の|多くの|個々の)方([、。にをはがもでへとやのからまでより（)】」』\s])",
        replace_kata,
        t,
    )

    # 4. Context-sensitive "一切行わない / 毎回行う / 〜を行う" ("行" read as "ぎょう" if truncated or adjacent)
    t = re.sub(r"行(わ|い|う|え|お)", r"おこな\1", t)

    # 5. Numbers + counters that macOS say can misread
    # e.g. "表1" -> "表イチ", "問1" -> "問イチ", "60歳" -> "60サイ"
    t = re.sub(r"([0-9０-９]+)歳", r"\1サイ", t)
    t = re.sub(r"1日(?=[0-9０-９一二三四五六七八九十]+回|あたり|当たり|の中で|中|の)", "イチニチ", t)
    t = re.sub(r"(?<![0-9０-９])1人", "ひとり", t)
    t = re.sub(r"(?<![0-9０-９])2人", "ふたり", t)

    return t


def clean(t):
    t = (
        t.replace("★", "")
        .replace("——", "、")
        .replace("―", "、")
        .replace(" ・", " ")
        .replace("。・", "。")
        .replace("→", "、つまり、")
        .replace("＝", "イコール")
        .replace("|", "、")
        .replace("｜", "、")
    )
    t = re.sub(r"\s+", " ", t)
    t = re.sub(r"([。、])\s*[。、]+", r"\1", t)
    t = re.sub(r"^[。、 ]+", "", t)
    t = normalize_japanese_readings(t)
    return t.strip()


